-- Hàm tự động tạo hồ sơ profile khi người dùng đăng ký qua Supabase Auth (có khối EXCEPTION an toàn)
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
SECURITY DEFINER
SET search_path = public
LANGUAGE plpgsql
AS $$
BEGIN
  INSERT INTO public.profiles (id, email, name, role, avatar_url, provider)
  VALUES (
    NEW.id,
    COALESCE(NEW.email, ''),
    COALESCE(NEW.raw_user_meta_data->>'name', NEW.raw_user_meta_data->>'full_name', split_part(COALESCE(NEW.email, ''), '@', 1), 'Người dùng'),
    CASE 
      WHEN NEW.raw_app_meta_data->>'role' IN ('USER', 'CUSTOMER', 'ADMIN', 'SECURITY_OFFICER') 
      THEN (NEW.raw_app_meta_data->>'role')::user_role 
      ELSE 'USER'::user_role 
    END,
    COALESCE(NEW.raw_user_meta_data->>'avatar_url', 'https://images.unsplash.com/photo-1535713875002-d1d0cf377fde?auto=format&fit=crop&w=160&q=80'),
    CASE 
      WHEN NEW.raw_app_meta_data->>'provider' IN ('GOOGLE', 'APPLE', 'FACEBOOK', 'TWITTER', 'CREDENTIALS') 
      THEN (NEW.raw_app_meta_data->>'provider')::auth_provider_type 
      ELSE 'CREDENTIALS'::auth_provider_type 
    END
  )
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    name = CASE WHEN public.profiles.name = '' THEN EXCLUDED.name ELSE public.profiles.name END,
    avatar_url = COALESCE(EXCLUDED.avatar_url, public.profiles.avatar_url),
    updated_at = now();
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  -- Bắt mọi ngoại lệ để không bao giờ làm gián đoạn lệnh đăng ký của auth.users
  RAISE WARNING 'handle_new_user trigger warning: %', SQLERRM;
  RETURN NEW;
END;
$$;

